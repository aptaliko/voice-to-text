import pytest

from app.dictation import apply_commands


@pytest.mark.parametrize(
    "spoken, written",
    [
        ("συμβόλαιο 1234 κάθετος 2020 τελεία ο πωλητής", "συμβόλαιο 1234/2020. Ο πωλητής"),
        ("ΚΑΕΚ 05 παύλα 001 παύλα 23", "ΚΑΕΚ 05-001-23"),
        ("Αθήνα παύλα Πειραιάς.", "Αθήνα - Πειραιάς."),
        ("ποσοστό 50 τοις εκατό εξ αδιαιρέτου", "ποσοστό πενήντα τοις εκατό (50%) εξ αδιαιρέτου"),
        ("ο αγοραστής άνω και κάτω τελεία Γεώργιος κόμμα του Ιωάννη", "ο αγοραστής: Γεώργιος, του Ιωάννη"),
        ("ο πωλητής, άνοιγμα παρένθεσης, εφεξής πωλητής, κλείσιμο παρένθεσης, δηλώνει", "ο πωλητής (εφεξής πωλητής) δηλώνει"),
        ("ο όρος ανοίγουν εισαγωγικά ως έχει κλείνουν εισαγωγικά τελεία", "ο όρος «ως έχει»."),
        ("είναι αληθές ερωτηματικό ναι", "είναι αληθές; Ναι"),
        ("ο αγοραστής άνω κάτω τελεία Γεώργιος", "ο αγοραστής: Γεώργιος"),
        ("ο αγοραστής, άνω-κάτω τελεία. Γεώργιος", "ο αγοραστής: Γεώργιος"),
        ("κατά το σύμβολο παραγράφου 3", "κατά το § 3"),
        ("Ο πωλητής. Τελεία. ο αγοραστής", "Ο πωλητής. Ο αγοραστής"),
        ("άρθρο τελεία νέα παράγραφος δεύτερο κόμμα νέα γραμμή τρίτο", "άρθρο.\n\nΔεύτερο,\nΤρίτο"),
        ("Κάθετος ΚΑΙ ΧΩΡΙΣ ΤΟΝΟΥΣ: 12 καθετος 3", "Κάθετος ΚΑΙ ΧΩΡΙΣ ΤΟΝΟΥΣ: 12/3"),
    ],
)
def test_spoken_symbols(spoken, written):
    assert apply_commands(spoken) == written


@pytest.mark.parametrize(
    "text",
    ["ο κάθετος τοίχος του κτιρίου", "ένα ακίνητο στην Αθήνα", "η τελειότητα και τα κόμματα"],
)
def test_everyday_words_are_left_alone(text):
    assert apply_commands(text) == text


@pytest.mark.parametrize(
    "spoken, written",
    [
        (
            "ο πωλητής δηλώνει ότι άνω και κάτω τελεία αρίθμηση ένα το ακίνητο είναι ελεύθερο κόμμα "
            "αρίθμηση 2 παρένθεση δεν υπάρχουν βάρη τελεία",
            "ο πωλητής δηλώνει ότι:\n1) το ακίνητο είναι ελεύθερο,\n2) δεν υπάρχουν βάρη.",
        ),
        (
            "οι όροι είναι άλφα παρένθεση πρώτος βήτα παρένθεση δεύτερος, γάμμα παρένθεση τρίτος στίγμα παρένθεση έκτος",
            "οι όροι είναι\nα) πρώτος\nβ) δεύτερος\nγ) τρίτος\nστ) έκτος",
        ),
        ("α παρένθεση πρώτο β παρένθεση δεύτερο", "α) πρώτο\nβ) δεύτερο"),
        ("κείμενο νέα γραμμή αρίθμηση 1 πρώτο", "κείμενο\n1) πρώτο"),
        ("κείμενο νέα παράγραφος αρίθμηση δώδεκα πρώτο", "κείμενο\n\n12) πρώτο"),
        ("αρίθμηση είκοσι ένα το ακίνητο", "21) το ακίνητο"),
        ("αρίθμηση βήτα δεύτερος", "β) δεύτερος"),
        ("ότι Αρίθμιση 1 πρώτο", "ότι\n1) πρώτο"),
        ("όροι αρίθμηση ένα το ακίνητο αρίθμηση δύο τα βάρη", "όροι\n1) το ακίνητο\n2) τα βάρη"),
    ],
)
def test_list_numbering(spoken, written):
    assert apply_commands(spoken) == written


def test_article_before_parenthesis_is_not_a_list_item():
    assert apply_commands("η παρένθεση είναι σημείο στίξης") == "η παρένθεση είναι σημείο στίξης"


@pytest.mark.parametrize(
    "spoken, written",
    [
        (
            "κεφαλαία γράμματα συμβόλαιο αγοραπωλησίας μικρά γράμματα νέα παράγραφος στην Αθήνα σήμερα",
            "ΣΥΜΒΟΛΑΙΟ ΑΓΟΡΑΠΩΛΗΣΙΑΣ\n\nΣτην Αθήνα σήμερα",
        ),
        (
            "Ο πωλητής, κεφαλαία γράμματα, Γεώργιος Παπαδόπουλος, μικρά γράμματα, κάτοικος Αθηνών",
            "Ο πωλητής ΓΕΩΡΓΙΟΣ ΠΑΠΑΔΟΠΟΥΛΟΣ κάτοικος Αθηνών",
        ),
        # Capitals keep the diaeresis but drop the accent.
        ("κεφαλαία γράμματα πρωτεΐνη και άρθρο πρώτο", "ΠΡΩΤΕΪΝΗ ΚΑΙ ΑΡΘΡΟ ΠΡΩΤΟ"),
        # Numbers still get their case from the word before the command.
        ("αντί κεφαλαία γράμματα 250.000 ευρώ μικρά γράμματα τελεία", "αντί ΔΙΑΚΟΣΙΩΝ ΠΕΝΗΝΤΑ ΧΙΛΙΑΔΩΝ ΕΥΡΩ (250.000 €)."),
        # «κεφαλαία» alone is the financial term, not a command.
        ("τα κεφαλαία της εταιρείας", "τα κεφαλαία της εταιρείας"),
    ],
)
def test_capitals_mode(spoken, written):
    assert apply_commands(spoken) == written
