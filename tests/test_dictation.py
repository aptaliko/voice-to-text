import pytest

from app.dictation import apply_commands, command_list


@pytest.mark.parametrize(
    "spoken, written",
    [
        ("συμβόλαιο 1234 κάθετος 2020 τελεία ο πωλητής", "συμβόλαιο 1234/2020. Ο πωλητής"),
        ("ΚΑΕΚ 05 παύλα 001 παύλα 23", "ΚΑΕΚ 05-001-23"),
        ("Αθήνα παύλα Πειραιάς.", "Αθήνα - Πειραιάς."),
        ("ποσοστό 50 τοις εκατό εξ αδιαιρέτου", "ποσοστό 50% εξ αδιαιρέτου"),
        ("ο αγοραστής άνω και κάτω τελεία Γεώργιος κόμμα του Ιωάννη", "ο αγοραστής: Γεώργιος, του Ιωάννη"),
        ("ο πωλητής, άνοιγμα παρένθεσης, εφεξής πωλητής, κλείσιμο παρένθεσης, δηλώνει", "ο πωλητής (εφεξής πωλητής) δηλώνει"),
        ("ο όρος ανοίγουν εισαγωγικά ως έχει κλείνουν εισαγωγικά τελεία", "ο όρος «ως έχει»."),
        ("είναι αληθές ερωτηματικό ναι", "είναι αληθές; Ναι"),
        ("κατά το σύμβολο παραγράφου 3", "κατά το § 3"),
        ("Ο πωλητής. Τελεία. ο αγοραστής", "Ο πωλητής. Ο αγοραστής"),
        ("άρθρο τελεία νέα παράγραφος δεύτερο κόμμα νέα γραμμή τρίτο", "άρθρο.\n\nΔεύτερο,\nΤρίτο"),
        ("Κάθετος ΚΑΙ ΧΩΡΙΣ ΤΟΝΟΥΣ: 12 καθετος 3", "Κάθετος ΚΑΙ ΧΩΡΙΣ ΤΟΝΟΥΣ: 12/3"),
    ],
)
def test_spoken_symbols(spoken, written):
    assert apply_commands(spoken) == written


@pytest.mark.parametrize(
    "text",
    ["ο κάθετος τοίχος του κτιρίου", "ποσοστό πενήντα τοις εκατό", "η τελειότητα και τα κόμματα"],
)
def test_everyday_words_are_left_alone(text):
    assert apply_commands(text) == text


def test_command_list_has_one_row_per_phrase():
    says = [row["say"] for row in command_list()]
    assert says.count("παύλα") == 1
    assert {"say": "κάθετος", "symbol": "/", "note": "δίπλα σε αριθμό: 1234/2020"} in command_list()
