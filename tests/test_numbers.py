import pytest

from app.dictation import apply_commands
from app.numbers import single_number, to_words


@pytest.mark.parametrize(
    "n, words",
    [
        (0, "μηδέν"),
        (1, "ένα"),
        (13, "δεκατρία"),
        (29, "είκοσι εννέα"),
        (100, "εκατό"),
        (101, "εκατόν ένα"),
        (1234, "χίλια διακόσια τριάντα τέσσερα"),
        (2026, "δύο χιλιάδες είκοσι έξι"),
        (21300, "είκοσι μία χιλιάδες τριακόσια"),
        (250000, "διακόσιες πενήντα χιλιάδες"),
        (304000, "τριακόσιες τέσσερις χιλιάδες"),
        (1500000, "ένα εκατομμύριο πεντακόσιες χιλιάδες"),
    ],
)
def test_to_words(n, words):
    assert to_words(n) == words


def test_to_words_genitive():
    assert to_words(3500, genitive=True) == "τριών χιλιάδων πεντακοσίων"
    assert to_words(1_000_000, genitive=True) == "ενός εκατομμυρίου"


@pytest.mark.parametrize(
    "words, value",
    [
        ("είκοσι εννέα", 29),
        ("διακοσίων πενήντα χιλιάδων", 250000),
        ("χίλια διακόσια τριάντα τέσσερα", 1234),
        ("δέκα τρία", 13),
        ("δύο τρία", None),
        ("είκοσι δώδεκα", None),
    ],
)
def test_single_number(words, value):
    assert single_number(words.split()) == value


@pytest.mark.parametrize(
    "spoken, written",
    [
        # Words keep the speaker's form and get the digits.
        ("εμβαδόν είκοσι εννέα τετραγωνικά μέτρα", "εμβαδόν είκοσι εννέα τετραγωνικά μέτρα (29 τ.μ.)"),
        # Square metres: spoken unit kept, abbreviations spelled out in the right case.
        ("εμβαδού ογδόντα πέντε τετραγωνικών μέτρων", "εμβαδού ογδόντα πέντε τετραγωνικών μέτρων (85 τ.μ.)"),
        ("εμβαδού 85 τ.μ. στον πρώτο όροφο", "εμβαδού ογδόντα πέντε τετραγωνικών μέτρων (85 τ.μ.) στον πρώτο όροφο"),
        ("έχει 85 τετραγωνικά μέτρα", "έχει ογδόντα πέντε τετραγωνικά μέτρα (85 τ.μ.)"),
        ("έχει ογδόντα πέντε τετραγωνικά", "έχει ογδόντα πέντε τετραγωνικά (85 τ.μ.)"),
        ("οικόπεδο εκτάσεως 1250 τ.μ.", "οικόπεδο εκτάσεως χιλίων διακοσίων πενήντα τετραγωνικών μέτρων (1.250 τ.μ.)"),
        ("αποθήκη 1 τ.μ.", "αποθήκη ένα τετραγωνικό μέτρο (1 τ.μ.)"),
        ("επιφανείας 120 m2", "επιφανείας εκατόν είκοσι τετραγωνικών μέτρων (120 τ.μ.)"),
        ("εμβαδού ογδόντα πέντε τετραγωνικών μέτρων (85 τ.μ.)", "εμβαδού ογδόντα πέντε τετραγωνικών μέτρων (85 τ.μ.)"),
        ("αντί 250.000 ευρώ", "αντί διακοσίων πενήντα χιλιάδων ευρώ (250.000 €)"),
        ("αντί τιμήματος διακοσίων πενήντα χιλιάδων ευρώ τελεία", "αντί τιμήματος διακοσίων πενήντα χιλιάδων ευρώ (250.000 €)."),
        ("ποσοστό πενήντα τοις εκατό εξ αδιαιρέτου", "ποσοστό πενήντα τοις εκατό (50%) εξ αδιαιρέτου"),
        ("το έτος δύο χιλιάδες είκοσι έξι", "το έτος δύο χιλιάδες είκοσι έξι (2026)"),
        # Digits from Whisper get the words.
        ("το τίμημα ορίζεται σε 250.000 ευρώ", "το τίμημα ορίζεται σε διακόσιες πενήντα χιλιάδες ευρώ (250.000 €)"),
        ("του ποσού των 3500 ευρώ", "του ποσού των τριών χιλιάδων πεντακοσίων ευρώ (3.500 €)"),
        ("έχει 3 δωμάτια", "έχει τρία (3) δωμάτια"),
        # Explicit parentheses give only the digit, and are not doubled.
        ("τα δύο άνοιγμα παρένθεσης δύο κλείσιμο παρένθεσης μέρη", "τα δύο (2) μέρη"),
        ("άνοιγμα παρένθεσης δύο κλείσιμο παρένθεσης", "(2)"),
        # References stay in digits.
        ("σύμφωνα με το άρθρο πέντε του νόμου 4412/2016", "σύμφωνα με το άρθρο 5 του νόμου 4412/2016"),
        ("ΑΦΜ 123456789 οδού Πατησίων 25 ΤΚ 11523", "ΑΦΜ 123456789 οδού Πατησίων 25 ΤΚ 11523"),
        ("Λεωφόρου Βασιλίσσης Σοφίας είκοσι πέντε, με 2 δωμάτια", "Λεωφόρου Βασιλίσσης Σοφίας 25, με δύο (2) δωμάτια"),
        ("στις 12/05/2026 και ώρα 10:30", "στις 12/05/2026 και ώρα 10:30"),
        ("χίλια διακόσια τριάντα τέσσερα κάθετος δύο χιλιάδες είκοσι", "1234/2020"),
        ("ΚΑΕΚ 05 παύλα 001", "ΚΑΕΚ 05-001"),
    ],
)
def test_contract_numbers(spoken, written):
    assert apply_commands(spoken) == written


def test_numbered_item_is_distinct_from_amount():
    assert apply_commands("ότι αρίθμηση δύο δύο ακίνητα") == "ότι\n2) δύο (2) ακίνητα"
